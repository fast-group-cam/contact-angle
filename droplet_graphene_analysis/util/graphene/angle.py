def inclination_norm_inf_autocor(
        carbons_traj: np.ndarray,
        cell_xy: np.ndarray | tuple[float, float],
        max_tau: int,
        calc_points: tuple[int, int] | int = 80, *,
        cutoff: float = CUTOFF_RADIUS,
        margin: float = (3 * C_C_DISTANCE)
        ) -> np.ndarray:
    """Calculates the infinite-time limit of the normalized autocorrelation function of the local
    inclination angle of the graphene sheet (wrt the z-axis), at a series of test points along the
    xy plane.

    Parameters
    ----------
    carbons_traj : ndarray
        The Cartesian coordinates of the carbon atoms over a trajectory, with shape (N_frames,
        N_carbon, 3).
    cell_xy : array_like
        The cell parameters along the x- and y-axes, expressed as [cell_x, cell_y].
    max_tau : int
        The maximum time interval to evaluate the autocorrelation function at, in number of frames;
        this should be not much more than 5ps worth of frames.
    calc_points : tuple[int, int] or int, optional
        The number of grid points to calculate the inclination angles at, either specified as a
        tuple of integers (N_x, N_y), or given as a single integer N_x = N_y. Defaults to (80, 80).
    **kwargs
        Extra arguments are passed directly to `calc_inclination_angles`.

    Returns
    -------
    norm_inf_autocor : ndarray
        An array of shape (N_x, N_y), representing the infinite-time limit of the normalized
        autocorrelation function, evaluated at the gridpoints generated by `generate_grid`.
    """

    N_x, N_y = cast_to_gridsize(calc_points)
    autocorr = np.zeros((max_tau, N_x, N_y), dtype=float)
    angles = calc_inclination_angles(carbons_traj, cell_xy, calc_points,
                                     cutoff=cutoff, margin=margin)

    autocorr[0] = np.mean(np.square(angles), axis=0)
    for tau in range(1, max_tau):
        autocorr[tau] = np.mean(angles[:-tau] * angles[tau:], axis=0)
    autocorr[:] /= autocorr[0]

    def exp_curve(x, A, k, c):
        return A * np.exp(-k * x) + c

    tau = np.array(range(max_tau))
    result = np.zeros((N_x, N_y), dtype=float)
    for i in range(N_x):
        for j in range(N_y):
            try:
                popt, _ = curve_fit(exp_curve, tau, autocorr[:,i,j], p0=(0.2, 0.5, 0.8))
                result[i,j] = max(popt[-1], 0.0)
            except RuntimeError:
                result[i,j] = 0.0
    return result
