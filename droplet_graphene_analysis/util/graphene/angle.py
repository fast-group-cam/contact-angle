def inclination_autocorrelations(
        carbons_traj: np.ndarray,
        cell_xy: np.ndarray | tuple[float, float],
        tau: int = 0,
        calc_points: tuple[int, int] | int = 80,
        **kwargs
        ) -> np.ndarray:
    """Calculates the autocorrelation function of the local inclination angle of the graphene sheet
    (wrt the z-axis) at a series of test points along the xy plane, and a specific time interval.

    Parameters
    ----------
    carbons_traj : ndarray
        The Cartesian coordinates of the carbon atoms over a trajectory, with shape (N_frames,
        N_carbon, 3).
    cell_xy : array_like
        The cell parameters along the x- and y-axes, expressed as [cell_x, cell_y].
    tau : int
        The time interval to evaluate the autocorrelation function at, in number of frames.
    calc_points : tuple[int, int] or int, optional
        The number of grid points to calculate the inclination angles at, either specified as a
        tuple of integers (N_x, N_y), or given as a single integer N_x = N_y. Defaults to (80, 80).
    **kwargs
        Extra arguments are passed directly to `calc_inclination_angles`.

    Returns
    -------
    autocor : ndarray
        An array of shape (N_x, N_y), representing the autocorrelation function evaluated at the
        gridpoints generated by `generate_grid` and tau.
    """

    if tau >= carbons_traj.shape[0]:
        warnings.warn(f'The provided tau ({tau}) is larger than the length of the trajectory ' +
                      f'({carbons_traj.shape[0]})!', RuntimeWarning)
        N_x, N_y = cast_to_gridsize(calc_points)
        return np.zeros((N_x, N_y), dtype=float)
    
    angles = calc_inclination_angles(carbons_traj, cell_xy, calc_points, **kwargs)
    if tau == 0:
        return np.mean(np.square(angles), axis=0)
    return np.mean(angles[:-tau] * angles[tau:], axis=0)
    
