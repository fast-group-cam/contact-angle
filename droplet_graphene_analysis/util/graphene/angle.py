def mean_inclination_angles(
        carbons_traj: np.ndarray,
        cell_xy: np.ndarray | tuple[float, float],
        calc_points: tuple[int, int] | int = 80,
        **kwargs
        ) -> np.ndarray:
    """Calculates the mean (time-averaged) local inclination angle of the graphene sheet (wrt the
    z-axis) at a series of test points along the xy plane.

    Parameters
    ----------
    carbons_traj : ndarray
        The Cartesian coordinates of the carbon atoms over a trajectory, with shape (N_frames,
        N_carbon, 3).
    cell_xy : array_like
        The cell parameters along the x- and y-axes, expressed as [cell_x, cell_y].
    calc_points : tuple[int, int] or int, optional
        The number of grid points to calculate the inclination angles at, either specified as a
        tuple of integers (N_x, N_y), or given as a single integer N_x = N_y. Defaults to (80, 80).
    **kwargs
        Extra arguments are passed directly to `calc_inclination_angles`.

    Returns
    -------
    mean_angles : ndarray
        An array of shape (N_x, N_y), representing the time-averaged local inclination angles
        evaluated at the gridpoints generated by `generate_grid`.
    """

    angles = calc_inclination_angles(carbons_traj, cell_xy, calc_points, **kwargs)
    return np.mean(angles, axis=0)

